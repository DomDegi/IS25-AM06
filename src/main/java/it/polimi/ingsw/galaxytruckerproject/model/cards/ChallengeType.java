package it.polimi.ingsw.galaxytruckerproject.model.cards;

/**
 * Enum representing different types of challenges a player may face during a card event.
 * Each type corresponds to a minimum requirement that must be met.
 */
public enum ChallengeType {

    /** Minimum required total cannon strength */
    MINIMUM_CANNON_STRENGTH,

    /** Minimum required number of crew members */
    MINIMUM_CREW_NUMBER,

    /** Minimum required engine power */
    MINIMUM_ENGINE_POWER
}
